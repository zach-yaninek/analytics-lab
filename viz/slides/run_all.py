#!/usr/bin/env python3
"""Draw the slide version of every chart (viz/slides/*_slide.py), write their speaker notes and check them.

Run:  cd /home/user/analytics-lab && python3 -I viz/slides/run_all.py
      (viz/run_all.py runs this after the full charts.) Each slide script also runs on its own, e.g.
      python3 -I viz/slides/zac_04_issue_mix_slide.py

Writes:
  viz/figures/slides/<name>.png        16:9 at 200 dpi, pseudonymous; same file name as the full chart in viz/figures/
  viz/figures/slides/speaker_notes.md  per slide, the definitions and caveats to say aloud
  deliverables/*_slide_REALNAMES.png   real customer names (gitignored; htm_07 and zac_02 only)

Checks, after drawing:
  1. consistency: numbers drawn on the slides agree with the data (style.check calls in the slide scripts);
  2. titles: each slide's title is drawn on its full chart too, so both state the same finding with the same numbers
     (the full charts are drawn into a temporary folder, unless viz/run_all.py passes the texts it already has);
  3. definitions: every term a slide uses has its definition in the slide's speaker notes (the full charts' check,
     with the speaker notes in place of the footer);
  4. privacy: no real customer name or serial appears on a pseudonymous slide or in the speaker notes.
A failed title, definition or privacy check raises RuntimeError.
"""
import importlib
import importlib.util
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
# python3 -I leaves the script directory off sys.path
sys.path[:0] = [str(HERE), str(HERE.parent / 'style'), str(HERE.parent / 'high_ticket'),
                str(HERE.parent / 'zac_notebook')]
import ipa_style as style  # noqa: E402
import slides  # noqa: E402

CHARTS = ['htm_01_concentration_curve', 'htm_02_tickets_per_machine', 'htm_03_observed_vs_expected',
          'htm_04_model_mix', 'htm_05_episode_followups', 'htm_06_pre_ticket',
          'htm_07_chronic_outliers_by_customer', 'htm_08_chronic_categories_heatmap', 'htm_09_tickets_by_type',
          'htm_10_ticket_rate_by_machine_type',
          'zac_01_missing_fields', 'zac_02_customer_workload', 'zac_03_model_workload', 'zac_04_issue_mix',
          'zac_05_machine_type_rates', 'zac_06_monthly_rates', 'zac_07_repeat_contact',
          'zac_08_customer_concentration', 'zac_09_model_issue_heatmap', 'zac_10_repeat_composition']
REAL_NAME_CHARTS = {'htm_07_chronic_outliers_by_customer', 'zac_02_customer_workload'}
SECTIONS = {'htm_': 'high_ticket', 'zac_': 'zac_notebook'}  # file-name prefix -> folder of the full charts
NOTES_FILE = 'speaker_notes.md'


def section(name):
    """Import viz/<name>/run_all.py under a unique module name (each section has a run_all.py)."""
    spec = importlib.util.spec_from_file_location(f'{name}_run_all', HERE.parent / name / 'run_all.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def full_chart_texts():
    """Draw the full charts into a temporary folder; return {file name: every string drawn on it}."""
    texts = {}
    with tempfile.TemporaryDirectory() as tmp:
        for name in SECTIONS.values():
            section(name).main(out_dir=tmp, private=False)
            texts.update({p.name: strings for p, strings in style.TEXTS.items()})
    return texts


def write_notes(out_dir, paths):
    """speaker_notes.md: for each slide, its title and the talking points its script recorded."""
    lines = ['# Speaker notes for the slide charts', '',
             'Generated by `viz/slides/run_all.py`; do not edit by hand. The slide charts leave out the definitions, '
             'caveats and sources that the full charts print in their footer; these notes list them so they can be '
             'said aloud. The full charts in `viz/figures/` remain the reference.', '']
    for p in paths:
        title, talk = slides.NOTES[p]
        lines += [f'## {p.name}', '', f'**{title}**', '', f'Full chart: `viz/figures/{p.name}`', '']
        lines += [f'- {t}' for t in talk] + ['']
    path = Path(out_dir) / NOTES_FILE
    path.write_text('\n'.join(lines))
    print(f'  wrote {path.relative_to(Path.cwd()) if path.is_relative_to(Path.cwd()) else path}')
    return path


def main(out_dir=slides.FIG_DIR, private=True, full_texts=None):
    out_dir = Path(out_dir)
    if full_texts is None:
        print('Full charts (for the title check) -> temporary folder ...')
        full_texts = full_chart_texts()
    print(f'Slide plots -> {out_dir} ...')
    style.CHECKS.clear()
    style.TEXTS.clear()
    slides.NOTES.clear()
    written = []
    for name in CHARTS:
        module = importlib.import_module(f'{name}_slide')
        if name in REAL_NAME_CHARTS:
            written += module.plot(out_dir=out_dir, private=private)
        else:
            written += module.plot(out_dir=out_dir)
    shown = [p for p in written if p.parent == out_dir]  # the pseudonymous slides
    notes = write_notes(out_dir, shown)

    n_ok = sum(ok for _, ok in style.CHECKS)
    print(f'  {len(written)} figures; consistency checks: {n_ok} pass, {len(style.CHECKS) - n_ok} warn')
    titles = [f'{p.name}: title is not on the full chart' for p in shown
              if slides.NOTES[p][0] not in full_texts.get(p.name, [])]
    print(f'  title check: {len(shown) - len(titles)} of {len(shown)} slides carry their full chart\'s title '
          f'({"PASS" if not titles else "FAIL"})')
    definitions = []
    for prefix, name in SECTIONS.items():
        definitions += section(name).definition_problems(
            {p: style.TEXTS[p] + slides.NOTES[p][1] for p in shown if p.name.startswith(prefix)})
    print(f'  definition check (speaker notes): {"PASS" if not definitions else "FAIL"}')
    for m in titles + definitions:
        print(f'    {m}')
    style.TEXTS[notes] = [notes.read_text()]
    scans = [section(name).privacy_scan(shown + [notes]) for name in SECTIONS.values()]
    leaks = None if all(s is None for s in scans) else sum(s or 0 for s in scans)
    if leaks is not None:
        print(f'  privacy scan of pseudonymous slides and speaker notes: {leaks} real names found '
              f'({"PASS" if leaks == 0 else "FAIL"})')
    if titles:
        raise RuntimeError('a slide title differs from its full chart\'s title')
    if definitions:
        raise RuntimeError('a slide uses a term its speaker notes do not define')
    if leaks:
        raise RuntimeError('a pseudonymous slide or the speaker notes contain a real customer name')
    return written


if __name__ == '__main__':
    main()
